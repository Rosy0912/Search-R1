"""Fresh common8 native pipeline; no old A800 counters or external GPU jobs.

Production launch requires full native allocation and a fresh bound manifest.
Every admission is generated by actual components, never preparation markers.
"""
import argparse,csv,fcntl,io,json,os,signal,socket,subprocess,threading,time,hashlib
from pathlib import Path
from reproduction.a800.owned_processes import OwnedProcesses,publish
from reproduction.common8.verify_data import digest
from reproduction.common8.stage_retrieval import binding,memory_bytes
ALLOWED=tuple(range(8))
_interrupt_requested=None


def request_interrupt(sig,frame):
    # Never raise asynchronously between Popen and durable ownership registration.
    global _interrupt_requested
    _interrupt_requested=sig


def gpu_rows(fields,kind='gpu'):
    return list(csv.reader(io.StringIO(subprocess.check_output(['nvidia-smi','--query-'+kind+'='+fields,'--format=csv,noheader,nounits'],text=True))))


class Pipeline:
    def __init__(self,base,run):
        self.base=base;self.run=run;self.repo=base/'repo';self.python=str(base/'env/bin/python')
        self.owned=OwnedProcesses(base/'logs/process-ledger.json',run['run_id'])
        allocation=json.loads((base/'logs/native-allocation-admission.json').read_text());self.physical_indices=set(allocation['actual_allocated_indices'])
        self.stop_sampling=threading.Event();self.max_used={};self.sample_error=None
        self.visible=os.environ['CUDA_VISIBLE_DEVICES'].split(',');assert len(self.visible)==8
        self.env=dict(os.environ,SEARCH_G1_PROFILE='common8',SEARCH_G1_BASE=str(base),PYTHONPATH=str(self.repo),PATH=str(base/'env/bin')+':'+os.environ['PATH'],
                      HF_HUB_OFFLINE='1',HF_DATASETS_OFFLINE='1',PYTHONUNBUFFERED='1',OMP_NUM_THREADS='8',
                      TMPDIR=str(base/'tmp'),RAY_TMPDIR=str(base/'ray'),HF_HOME=str(base/'cache/hf'),XDG_CACHE_HOME=str(base/'cache'),
                      TRITON_CACHE_DIR=str(base/'cache/triton'),TORCHINDUCTOR_CACHE_DIR=str(base/'cache/inductor'),
                      C_INCLUDE_PATH=str(base/'bootstrap-tools/python-dev/usr/include/python3.10')+':'+str(base/'bootstrap-tools/python-dev/usr/include'),
                      NCCL_NVLS_ENABLE='0',VLLM_ATTENTION_BACKEND='XFORMERS',NO_PROXY='127.0.0.1,localhost')
        for key in ('PYTHONHOME','RAY_ADDRESS','HTTP_PROXY','HTTPS_PROXY','ALL_PROXY','http_proxy','https_proxy','all_proxy'):self.env.pop(key,None)
    def stage(self,name,**extra):publish(self.base/'logs/pipeline-status.json',dict(run_id=self.run['run_id'],stage=name,unix=time.time(),**extra))
    def sample(self):
        path=self.base/'logs'/('gpu-samples-'+self.run['run_id']+'.jsonl')
        try:
            with path.open('a') as f:
                while not self.stop_sampling.is_set():
                    rows=[]
                    for r in gpu_rows('index,memory.used,memory.total,utilization.gpu'):
                        if int(r[0]) in self.physical_indices:
                            item=dict(index=int(r[0]),used_mib=int(r[1]),total_mib=int(r[2]),util_percent=int(r[3]));rows.append(item)
                            self.max_used[item['index']]=max(self.max_used.get(item['index'],0),item['used_mib'])
                    f.write(json.dumps(dict(run_id=self.run['run_id'],unix=time.time(),gpus=rows))+'\n');f.flush()
                    self.stop_sampling.wait(2)
        except Exception as e:self.sample_error=repr(e)
    def start(self,name,args,gpus,extra=None):
        assert _interrupt_requested is None, 'Pipeline stop requested before component launch'
        assert set(gpus)<=set(ALLOWED)
        env=dict(self.env,CUDA_VISIBLE_DEVICES=','.join(self.visible[i] for i in gpus));env.update(extra or {})
        process=self.owned.start(name,args,env,self.base/'logs'/(name+'.log'),self.repo)
        self.observe_all() # Deferred stop can now safely clean this registered child.
        return process
    def observe_all(self):
        for name,job in self.owned.jobs.items():
            if job['state']!='STOPPED':self.owned.observe(name)
        assert _interrupt_requested is None, 'Pipeline interrupted; clean up registered owned processes'
        assert self.sample_error is None, 'GPU sampling failed: '+str(self.sample_error)
    def wait(self,name,process,timeout=None):
        started=time.monotonic()
        while True:
            self.observe_all() # before poll can reap a session leader
            code=process.poll()
            if code is not None:
                self.owned.jobs[name]['exit_code']=code;self.owned.save()
                assert code==0, name+' failed; see project log'
                assert not self.owned.observe(name), name+' left owned subprocesses'
                self.owned.jobs[name]['state']='STOPPED';self.owned.save()
                return
            if timeout:assert time.monotonic()-started<timeout, name+' exceeded admission timeout'
            time.sleep(1)
    def endpoint(self,name,process,path,method='get',payload=None):
        import requests
        session=requests.Session();session.trust_env=False;started=time.monotonic()
        while True:
            self.observe_all();assert process.poll() is None, name+' exited during endpoint readiness'
            try:
                response=session.request(method,'http://127.0.0.1:'+path,json=payload,timeout=10);response.raise_for_status();return response.json()
            except requests.RequestException:
                assert time.monotonic()-started<1800, name+' endpoint readiness failed'
                time.sleep(2)
    def smoke(self, phase):
        p=self.start('model-'+phase,[self.python,'-m','torch.distributed.run','--standalone','--nproc_per_node=8','-m','reproduction.common8.model_smoke','--phase',phase],ALLOWED)
        self.wait('model-'+phase,p,3600)
        path=self.base/'logs'/('model-smoke-'+phase)/'complete.json'
        proof=json.loads(path.read_text())
        assert proof['accepted'] is True and proof['run_id']==self.run['run_id']
        assert proof['slurm_job_id']==os.environ['SLURM_JOB_ID'] and proof['phase']==phase
        return path
    def execute(self, export_port):
        sampler=threading.Thread(target=self.sample,daemon=True);sampler.start()
        success=False
        try:
            self.stage('EIGHT_RANK_MECHANICS')
            root=self.base/'logs/eight-rank-mechanics';root.mkdir(exist_ok=False)
            p=self.start('gpu-preflight',[self.python,'-m','torch.distributed.run','--standalone','--nproc_per_node=8','reproduction/common8/gpu_preflight.py'],ALLOWED,{'SEARCH_G1_GPU_PREFLIGHT_DIR':str(root)})
            self.wait('gpu-preflight',p,900)
            proofs=[json.loads((root/f'rank-{rank}.json').read_text()) for rank in range(8)]
            assert all(p['accepted'] is True and p['rank']==r and p['slurm_job_id']==os.environ['SLURM_JOB_ID'] for r,p in enumerate(proofs))
            self.stage('INITIAL_ACTOR_REFERENCE_ROLLOUT_SMOKE')
            smoke=self.smoke('initial')
            publish(self.base/'logs/eight-rank-admission.json',dict(accepted=True,run_id=self.run['run_id'],slurm_job_id=os.environ['SLURM_JOB_ID'],mechanics_sha256={str(r):digest(root/f'rank-{r}.json') for r in range(8)},model_smoke_sha256=digest(smoke),actual_grpo_updates=0))
            self.stage('STAGING_SAME_CLUSTER_ORIGINAL_RETRIEVAL')
            p=self.start('retrieval-stage',[self.python,'-m','reproduction.common8.stage_retrieval','--base',str(self.base),'--port',str(export_port)],[])
            self.wait('retrieval-stage',p)
            self.stage('STARTING_ORIGINAL_EIGHT_SHARD_FAISS')
            libs=list((self.base/'env/lib/python3.10/site-packages/nvidia').glob('*/lib'))+[self.base/'env/lib/python3.10/site-packages/torch/lib']
            p=self.start('retriever',[self.python,'-m','reproduction.common8.retriever'],ALLOWED,{'PYTHONPATH':str(self.base/'retriever-gpu-lib')+':'+str(self.repo),'LD_LIBRARY_PATH':':'.join(map(str,libs))})
            health=self.endpoint('retriever',p,'18010/health')
            assert health['ok'] is True and health['run_id']==self.run['run_id'] and health['shard_count']==8
            assert health['slurm_job_id']==os.environ['SLURM_JOB_ID']
            admission=self.base/'logs/retrieval-admission.json';assert health['admission_sha256']==digest(admission)
            # HTTP path itself must return the same actual stage64 documents/scores.
            from reproduction.common8.http_retrieval import admit_http
            admit_http(self.base)
            self.run['probe_visible_device']=self.visible[7]
            self.run['probe_logical_ordinal']=7
            publish(self.base/'logs/run-manifest.json',self.run)
            self.stage('REAL_INITIAL_300_QUESTION_CALIBRATION')
            c=self.start('initial-calibration',[self.python,'-m','reproduction.common8.refit','--step','0','--model',self.run['initial_model']],[7]);self.wait('initial-calibration',c)
            e=self.start('probe-server',[self.python,'probe_server.py','--manifest',str(self.base/'artifacts/live/manifest.json'),'--port','18012'],[7])
            health=self.endpoint('probe-server',e,'18012/health');assert health['ok'] is True
            released=self.endpoint('probe-server',e,'18012/suspend','post',{'version':health['version']})
            assert released['suspended'] is True and released['allocated_bytes_after_release']<256*1024*1024
            resumed=self.endpoint('probe-server',e,'18012/resume','post',{'version':health['version']})
            assert resumed['resumed'] is True and resumed['version']==health['version']
            publish(self.base/'logs/evaluator-release-admission.json',dict(run_id=self.run['run_id'],released=released,resumed=resumed))
            self.stage('REAL_MODEL_RETRIEVER_PROBE_COEXISTENCE')
            smoke=self.smoke('coexistence')
            totals={int(r[0]):int(r[1]) for r in gpu_rows('index,memory.total')}
            assert set(self.max_used)==self.physical_indices and all(v/totals[i]<=.98 for i,v in self.max_used.items())
            publish(self.base/'logs/probe-coexistence-admission.json',dict(accepted=True,run_id=self.run['run_id'],slurm_job_id=os.environ['SLURM_JOB_ID'],model_smoke_sha256=digest(smoke),sampled_peak_mib=self.max_used,scope='actual initial/coexistence sampled occupancy; not full 2560-trajectory peak'))
            a=self.start('probe-admission',[self.python,'-m','reproduction.common8.probe_admission'],[7]);self.wait('probe-admission',a,300)
            self.stage('GRPO_1_TO_300')
            log=Path(self.run['train_log'])
            assert not log.exists(), 'Canonical trainer log belongs to the claimed trainer, not preparation'
            t=self.start('trainer',['bash','reproduction/common8/train.sh'],ALLOWED,{'SEARCH_G1_TRAIN_LOG':str(log)});self.wait('trainer',t)
            self.stage('FINAL300_COMPLETE_SHARED_EVALUATION_ACCEPTANCE')
            v=self.start('final-acceptance',[self.python,'-m','reproduction.common8.verify_full','--base',str(self.base)],[]);self.wait('final-acceptance',v)
            success=True
        except Exception as error:
            self.stage('FAILED',error=repr(error));raise
        finally:
            try:
                self.owned.stop_all()
                from reproduction.common8.temporary_cache import cleanup as clean_cache
                from reproduction.common8.stage_retrieval import cleanup as clean_stage
                if (self.base/'logs/corpus-cache-claim.json').exists():clean_cache(self.base)
                if (self.base/'logs/retrieval-staging-claim.json').exists():clean_stage(self.base)
                recorded={r['pid'] for job in self.owned.jobs.values() for r in job['ledger'].values()}
                assert not [r for r in gpu_rows('gpu_uuid,pid','compute-apps') if int(r[1]) in recorded]
                publish(self.base/'logs/cleanup-status.json',dict(run_id=self.run['run_id'],cleaned=True,checked_unix=time.time()))
            except Exception as error:
                self.stage('OWNED_CLEANUP_FAILED',error=repr(error));raise
            finally:self.stop_sampling.set();sampler.join(5)
        if success:self.stage('FINISHED_FULL300_FINAL51713_AND_OWNED_CLEANUP')


def main():
    ap=argparse.ArgumentParser();ap.add_argument('--base',type=Path,required=True);ap.add_argument('--export-port',type=int,required=True);a=ap.parse_args()
    base=a.base.resolve();assert 1024<=a.export_port<=65535
    for name in ('logs','tmp','ray','cache/triton','cache/inductor','cache/hf','artifacts'):(base/name).mkdir(parents=True,exist_ok=True)
    lock=(base/'gpu-job.lock').open('a');fcntl.flock(lock,fcntl.LOCK_EX|fcntl.LOCK_NB)
    signal.signal(signal.SIGTERM,request_interrupt);signal.signal(signal.SIGINT,request_interrupt)
    run=json.loads((base/'logs/run-manifest.json').read_text())
    assert run['profile']=='common8' and run['completed_updates']==0 and run['initial_probe_version'] is None
    assert not (base/'logs/process-ledger.json').exists(), 'Inspect/clean previous attempt; never duplicate launch'
    for name,sha in run['source_sha256'].items():assert digest(base/'repo'/name)==sha
    for port in (18010,18012):
        with socket.socket() as sock:sock.bind(('127.0.0.1',port))
    from reproduction.common8.native_allocation import admit
    admit(base)
    _,job,_=binding(base);assert memory_bytes(job['TRES'])>=512*2**30
    from reproduction.common8.disk_admission import admit as admit_disk
    admit_disk(base)
    Pipeline(base,run).execute(a.export_port)

if __name__=='__main__':main()
